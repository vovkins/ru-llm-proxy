def test_validation_failure_preserves_previous_generated_file(tmp_path):
    base_path, profiles_path, output_path, _ = _generate(tmp_path)
    previous = output_path.read_bytes()
    profiles_path.write_text("schema_version: 2\n", encoding="utf-8")

    with pytest.raises(generator.ConfigGenerationError):
        generator.generate_config(
            base_path=base_path,
            profiles_path=profiles_path,
            output_path=output_path,
        )

    assert output_path.read_bytes() == previous


def test_failed_atomic_write_preserves_previous_file(tmp_path, monkeypatch):
    base_path, profiles_path, output_path, _ = _generate(tmp_path)
    previous = output_path.read_bytes()

    def fail_replace(source_path, destination_path):
        raise OSError("synthetic replace failure")

    monkeypatch.setattr(generator.os, "replace", fail_replace)
    with pytest.raises(generator.ConfigGenerationError, match="cannot write"):
        generator.generate_config(
            base_path=base_path,
            profiles_path=profiles_path,
            output_path=output_path,
        )

    assert output_path.read_bytes() == previous
    assert not list(output_path.parent.glob(f".{output_path.name}.*"))


def test_generator_refuses_to_replace_an_input_file(tmp_path):
    base_path = tmp_path / "base.yaml"
    profiles_path = tmp_path / "profiles.yaml"
    _write_yaml(base_path, _base_config())
    _write_yaml(profiles_path, _profile_config())
    original = base_path.read_bytes()

    with pytest.raises(generator.ConfigGenerationError, match="must not replace"):
        generator.generate_config(
            base_path=base_path,
            profiles_path=profiles_path,
            output_path=base_path,
        )

    assert base_path.read_bytes() == original


